// National Railways map builder.
// Makes js/map-<state>.js from U.S. Census Bureau county boundaries (the us-atlas package).
//
// Usage (from the national-railways folder):
//   cd tools && npm install && cd ..
//   node tools/build-map.js tools/node_modules CA
//
// To add a state later: add an entry to STATES below, run the script, and list the
// state's county stations in js/cities.js.
"use strict";
const fs = require("fs");
const path = require("path");

const MODULES = path.resolve(process.argv[2] || path.join(__dirname, "node_modules"));
const STATE = (process.argv[3] || "CA").toUpperCase();

const STATES = {
  CA: {
    fips: "06",
    name: "California",
    file: "map-california.js",
    // Counties under 50,000 people joined with neighbors they share a border with (at most 3).
    merge: [
      ["Del Norte", "Siskiyou", "Trinity"],
      ["Lassen", "Modoc"],
      ["Plumas", "Sierra"],
      ["Colusa", "Glenn"],
      ["Alpine", "Amador", "Calaveras"],
      ["Inyo", "Mono"],
      ["Mariposa", "Tuolumne"],
    ],
  },
};

const cfg = STATES[STATE];
if (!cfg) throw new Error(`Unknown state ${STATE}. Known: ${Object.keys(STATES).join(", ")}`);
const topo = JSON.parse(fs.readFileSync(path.join(MODULES, "us-atlas", "counties-10m.json"), "utf8"));
const tc = require(path.join(MODULES, "topojson-client"));

// Every county of the state, and the map region it belongs to.
const counties = topo.objects.counties.geometries.filter((g) => String(g.id).startsWith(cfg.fips));
const regionName = new Map(counties.map((g) => [g, g.properties.name]));
for (const group of cfg.merge) {
  const neighbors = tc.neighbors(counties);
  const members = group.map((n) => {
    const i = counties.findIndex((g) => g.properties.name === n);
    if (i < 0) throw new Error(`No county called ${n} in ${cfg.name}`);
    return i;
  });
  // A merged group must be connected: every member borders another member.
  for (const i of members) {
    if (members.length > 1 && !members.some((j) => j !== i && neighbors[i].includes(j))) {
      throw new Error(`${counties[i].properties.name} does not border the rest of its group`);
    }
  }
  const name = group.slice().sort().join("-");
  members.forEach((i) => regionName.set(counties[i], name));
}

// Round to 3 decimals (about 100 m) and drop repeated points.
const flat = (ring) => {
  const out = [];
  let lastX = null;
  let lastY = null;
  for (const [x, y] of ring) {
    const rx = Math.round(x * 1000) / 1000;
    const ry = Math.round(y * 1000) / 1000;
    if (rx === lastX && ry === lastY) continue;
    out.push(rx, ry);
    lastX = rx;
    lastY = ry;
  }
  return out;
};

// Land: all counties joined into one shape (with islands).
const land = tc.merge(topo, counties);
const landRings = land.coordinates.flatMap((poly) => poly.map(flat));

// Borders between different regions (not inside merged groups, not the coastline).
const mesh = tc.mesh(topo, { type: "GeometryCollection", geometries: counties }, (a, b) => a !== b && regionName.get(a) !== regionName.get(b));
const borders = mesh.coordinates.map(flat);

// One label point per region: the centroid of its largest piece.
const cosLat = Math.cos((37 * Math.PI) / 180);
function centroid(ring) {
  let a = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [x0, y0] = [ring[j][0] * cosLat, ring[j][1]];
    const [x1, y1] = [ring[i][0] * cosLat, ring[i][1]];
    const f = x0 * y1 - x1 * y0;
    a += f;
    cx += (x0 + x1) * f;
    cy += (y0 + y1) * f;
  }
  return { area: Math.abs(a / 2), lon: cx / (3 * a) / cosLat, lat: cy / (3 * a) };
}
const regions = [...new Set(regionName.values())].sort().map((name) => {
  const members = counties.filter((g) => regionName.get(g) === name);
  const shape = tc.merge(topo, members);
  const best = shape.coordinates.map((poly) => centroid(poly[0])).sort((a, b) => b.area - a.area)[0];
  return {
    id: name.toLowerCase().replace(/[^a-z]+/g, "-"),
    name: `${name} County`,
    fips: members.map((g) => String(g.id)).sort(),
    label: [Math.round(best.lon * 100) / 100, Math.round(best.lat * 100) / 100],
  };
});

const points = landRings.reduce((n, r) => n + r.length / 2, 0) + borders.reduce((n, r) => n + r.length / 2, 0);
const header = [
  `// ${cfg.name} map for National Railways: land, county borders and county regions.`,
  "// Generated by tools/build-map.js from U.S. Census Bureau county boundaries (us-atlas 3.0.1).",
  "// Do not edit by hand: change tools/build-map.js and run it again.",
  "// Rings and borders are flat lists of longitude, latitude pairs.",
].join("\n");
const body = `window.NR = window.NR || {};
NR.MAP = {
  state: ${JSON.stringify(cfg.name)},
  regions: [
${regions.map((r) => "    " + JSON.stringify(r)).join(",\n")}
  ],
  land: [
${landRings.map((r) => "    " + JSON.stringify(r)).join(",\n")}
  ],
  borders: [
${borders.map((r) => "    " + JSON.stringify(r)).join(",\n")}
  ],
};
`;
const out = path.join(__dirname, "..", "js", cfg.file);
fs.writeFileSync(out, `${header}\n${body}`);
console.log(`Wrote ${path.relative(process.cwd(), out)}: ${regions.length} regions from ${counties.length} counties, ${landRings.length} land rings, ${borders.length} border lines, ${points} points, ${Math.round(fs.statSync(out).size / 1024)} KB`);
